// NumberFormattingConformance.swift
// JeffJS — "NumberFormatting": Number.prototype.toFixed / toExponential /
// toPrecision (ECMA-262 §21.1.3.2, §21.1.3.3, §21.1.3.5) and ToIntegerOrInfinity
// on builtin arguments.
//
// toPrecision used to strip trailing zeros ((0.8).toPrecision(4) gave "0.8",
// spec "0.8000"; netflix's emotion styles hash "rgba(0,0,0,0.8000)"), its
// floor(log10) exponent could be off by one next to a power of ten, and all
// three rounded through floating-point scaling or printf's round-half-even
// instead of the spec's "pick the larger n" on the exact value. They now
// round the exact decimal expansion of the double half up. The argument is
// converted with ToIntegerOrInfinity before the finiteness check (valueOf runs
// even for NaN), RangeErrors are real RangeError objects (they were thrown as
// plain strings), and string/object arguments are converted (ctx.toInteger
// used to turn every non-number into 0: 'abc'.charAt('1') was "a").
//
// Every case is (name, JS expression that must evaluate to `true`); expected
// strings are QuickJS's (identical to V8's).

